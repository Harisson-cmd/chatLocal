-- V1 : utilisateurs (héritage JOINED : une table par classe, comme les entités de Harisson).
-- IF NOT EXISTS : certaines bases ont déjà ces tables, créées avant Flyway par Hibernate.

CREATE TABLE IF NOT EXISTS utilisateur (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant   VARCHAR(50)  NOT NULL UNIQUE,
    mot_de_passe  VARCHAR(255) NOT NULL,          -- toujours haché (BCrypt)
    nom           VARCHAR(100) NOT NULL,
    filiere       VARCHAR(100),
    niveau        VARCHAR(50),
    role          VARCHAR(20)  NOT NULL,
    statut        VARCHAR(20)  NOT NULL,
    date_creation TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS etudiant (
    id BIGINT PRIMARY KEY REFERENCES utilisateur(id)
);

CREATE TABLE IF NOT EXISTS enseignant (
    id          BIGINT PRIMARY KEY REFERENCES utilisateur(id),
    est_delegue BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS administrateur (
    id BIGINT PRIMARY KEY REFERENCES utilisateur(id)
);

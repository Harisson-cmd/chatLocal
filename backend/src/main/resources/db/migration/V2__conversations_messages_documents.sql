-- Conversation (classe mère). Groupe viendra plus tard : il suffira d'ajouter 'GROUPE' au CHECK.
CREATE TABLE conversation (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_conversation      VARCHAR(20) NOT NULL CHECK (type_conversation IN ('PRIVEE')),
    date_creation          TIMESTAMP   NOT NULL,
    date_derniere_activite TIMESTAMP   NOT NULL,
    cle_privee             VARCHAR(40) UNIQUE   -- ex. "3-7" : une seule conversation privée par paire
);

-- Association "participe à" (Utilisateur * -- 2..* Conversation)
CREATE TABLE conversation_participant (
    conversation_id BIGINT NOT NULL REFERENCES conversation(id),
    utilisateur_id  BIGINT NOT NULL REFERENCES utilisateur(id),
    PRIMARY KEY (conversation_id, utilisateur_id)
);
CREATE INDEX idx_participant_utilisateur ON conversation_participant(utilisateur_id);

CREATE TABLE document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fichier     VARCHAR(255) NOT NULL,
    chemin_stockage VARCHAR(500) NOT NULL UNIQUE,
    type_mime       VARCHAR(100) NOT NULL,
    taille_octets   BIGINT       NOT NULL,
    date_depot      TIMESTAMP    NOT NULL,
    auteur_id       BIGINT       NOT NULL REFERENCES utilisateur(id),
    matiere_id      BIGINT       -- optionnel, réservé au classement par matière (plus tard)
);
CREATE INDEX idx_document_date ON document(date_depot DESC);

CREATE TABLE message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client       VARCHAR(36) NOT NULL UNIQUE,   -- UUID créé par le client : anti-doublon
    conversation_id BIGINT      NOT NULL REFERENCES conversation(id),
    auteur_id       BIGINT      NOT NULL REFERENCES utilisateur(id),
    contenu         TEXT,
    date_envoi      TIMESTAMP   NOT NULL,
    statut          VARCHAR(20) NOT NULL CHECK (statut IN ('EN_ATTENTE','ENVOYE')),
    document_id     BIGINT REFERENCES document(id)
);
CREATE INDEX idx_message_conversation ON message(conversation_id, id DESC);
